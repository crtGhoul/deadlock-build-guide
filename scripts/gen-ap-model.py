#!/usr/bin/env python3
"""Generate scripts/ap-model.json — the Deadlock AP (ability point) economy.

Sources (both recorded in the output):
  * Game data: GET https://api.deadlock-api.com/v1/assets/heroes
    (each hero's `level_info`: per-level required_gold + bonus_currencies)
    and .../v1/assets/items (ability class_name -> display name, used to map
    each hero's `items.signature4` class to its ultimate's display name).
  * deadlock.wiki/Boons — the human-readable cross-check; its table matches
    the game data exactly (verified 2026-10-23: 36 level-ups, unlocks at
    600/1,100/2,000/3,800 gathered souls, 32 AP total, max boon level 35).

Model encoded:
  * Every player starts at 600 gathered souls (level 1) with an ability
    unlock in hand. Souls gathered only ever increase (spending at the shop
    does not reduce the gathered total).
  * level_info `required_gold` is cumulative souls BEYOND the starting 600,
    so a level's souls threshold = 600 + required_gold. The table is
    identical for all 44 heroes (asserted below).
  * Each ability has 3 upgrade tiers costing 1 / 2 / 5 AP (cumulative
    1 / 3 / 8 AP in that ability). AP is fungible and can be saved.
  * The first three unlocks can only go to non-ultimate abilities; the
    ultimate needs the 4th unlock (3,800 souls).

Usage: python3 scripts/gen-ap-model.py   (writes scripts/ap-model.json)
"""
import json
import os
import sys
import urllib.request

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEROES_URL = "https://api.deadlock-api.com/v1/assets/heroes"
ITEMS_URL = "https://api.deadlock-api.com/v1/assets/items"
WIKI_URL = "https://deadlock.wiki/Boons"


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "deadlock-build-guide/ap-model"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def main():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    ability_names = json.load(open(os.path.join(BASE, "scripts", "ability-names.json")))
    heroes = fetch(HEROES_URL)
    items = fetch(ITEMS_URL)
    class_to_name = {e["class_name"]: e["name"] for e in items}

    roster = [h for h in heroes if h.get("name") in ability_names]
    assert len(roster) == 44, f"expected 44 roster heroes, got {len(roster)}"

    # --- level table (must be identical for every hero) ---
    def table(hero):
        out = []
        for lv, info in sorted(hero["level_info"].items(), key=lambda kv: int(kv[0])):
            curs = info.get("bonus_currencies", [])
            reward = "unlock" if "EAbilityUnlocks" in curs else "ap"
            out.append({"level": int(lv), "souls": 600 + int(info["required_gold"]),
                        "reward": reward})
        return out

    levels = table(roster[0])
    for h in roster:
        assert table(h) == levels, f"level_info differs for {h['name']}"
    assert len(levels) == 36, f"expected 36 level-ups, got {len(levels)}"
    assert sum(1 for l in levels if l["reward"] == "ap") == 32
    assert sum(1 for l in levels if l["reward"] == "unlock") == 4

    # --- ultimate per hero: items.signature4 class -> display name ---
    ults = {}
    for h in roster:
        cls = (h.get("items") or {}).get("signature4")
        name = class_to_name.get(cls)
        assert name, f"{h['name']}: signature4 {cls!r} has no display name"
        assert name in ability_names[h["name"]], f"{h['name']}: ult {name!r} not in ability list"
        ults[h["name"]] = name

    model = {
        "_doc": "Deadlock ability-point economy. Generated by scripts/gen-ap-model.py — do not hand-edit.",
        "sources": [HEROES_URL, ITEMS_URL, WIKI_URL],
        "start_souls": 600,
        "max_boon_level": 35,
        "levels": levels,
        "unlock_souls": [l["souls"] for l in levels if l["reward"] == "unlock"],
        "total_ap": 32,
        "tier_costs": [1, 2, 5],
        "tier_at_ap": [1, 3, 8],
        "ultimates": ults,
        "assumptions": [
            "A build's 16-step track reads as a chronological spend sequence: an ability's first step is its unlock, every later step is +1 AP into it.",
            "Saving is legal: AP and unlocks can be held, so a spend sequence is fundable iff the greedy earliest simulation (advance level-ups only when a spend cannot be afforded) never runs out of level-ups.",
            "Ultimate rule (wiki + game data): the first three unlocks can only go to non-ultimate abilities; the ultimate takes the 4th unlock (3,800 gathered souls).",
        ],
    }
    out = os.path.join(BASE, "scripts", "ap-model.json")
    with open(out, "w") as f:
        json.dump(model, f, indent=1)
    print(f"wrote {out}: {len(levels)} levels, unlocks at {model['unlock_souls']}, "
          f"total AP {model['total_ap']}, ults for {len(ults)} heroes")


if __name__ == "__main__":
    main()
